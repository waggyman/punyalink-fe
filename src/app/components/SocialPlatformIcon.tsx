const LUCIDE_BY_PLATFORM: Partial<Record<SocialPlatform, LucideIcon>> = {
  instagram: Instagram,
  facebook: Facebook,
  youtube: Youtube,
  linkedin: Linkedin,
  whatsapp: MessageCircle,
  telegram: Send,
  twitch: Twitch,
  spotify: Music,
  github: Github,
  website: Globe,
};

const BRAND_BY_PLATFORM: Partial<
  Record<SocialPlatform, ComponentType<BrandIconProps>>
> = {
  tiktok: TikTokIcon,
  x: XIcon,
  pinterest: PinterestIcon,
  snapchat: SnapchatIcon,
  threads: ThreadsIcon,
  discord: DiscordIcon,
  behance: BehanceIcon,
  dribbble: DribbbleIcon,
};

export function SocialPlatformIcon({
  platform,
  className = "size-5",
}: SocialPlatformIconProps) {
  const Brand = BRAND_BY_PLATFORM[platform];
  if (Brand) {
    return <Brand className={className} />;
  }
  const Lucide = LUCIDE_BY_PLATFORM[platform];
  if (Lucide) {
    return <Lucide className={className} aria-hidden />;
  }
  return <Globe className={className} aria-hidden />;
}
